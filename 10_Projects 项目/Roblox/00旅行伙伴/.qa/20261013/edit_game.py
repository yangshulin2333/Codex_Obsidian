changes = []


def edit(index, text, style=None):
    p = Paragraph(blocks[index], doc)
    before = p.text
    p.text = text
    if style:
        p.style = style
    changes.append({'block': index, 'before': before, 'after': text})
    return p


def insert_after(index, items):
    anchor = blocks[index]
    for style, text in items:
        node = OxmlElement('w:p')
        anchor.addnext(node)
        p = Paragraph(node, doc)
        p.style = style
        p.text = text
        anchor = node


