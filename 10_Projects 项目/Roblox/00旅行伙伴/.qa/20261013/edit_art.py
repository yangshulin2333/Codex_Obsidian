def c(table, row, col, value):
    cell = ts[table].cell(row, col)
    changes.append({'cell': [table, row, col], 'before': cell.text, 'after': value})
    cell.text = value


def insert_after(anchor, text, style=None):
    item = doc.add_paragraph(text, style)
    anchor.addnext(item._p)
    return item._p


